// Minimal bundler for the compiler's own source files, so the playground
// page can run entirely client-side with zero build tooling / npm deps in
// the browser (only wabt's browser build is loaded separately via <script>).
//
// This purposefully avoids webpack/rollup/esbuild: for a compiler-design
// course project the interesting code is the compiler itself, not the
// bundler, so this stays a ~40-line script instead of a dependency.
//
// How it works: each src/*.js file is wrapped in a function(module, exports,
// require) closure, mimicking Node's own module wrapper. A tiny runtime at
// the top implements `require("./name")` by looking up already-defined
// modules in a registry. Order doesn't matter since requires are resolved
// lazily on first use.

const fs = require("fs");
const path = require("path");

const SRC_DIR = path.join(__dirname, "src");
const OUT_FILE = path.join(__dirname, "playground", "compiler.bundle.js");

const files = ["tokens.js", "lexer.js", "ast.js", "parser.js", "scope.js", "analyzer.js", "codegen.js"];

let out = `// AUTO-GENERATED by build-playground.js — do not edit directly.
// Source of truth is src/*.js; re-run "node build-playground.js" after changes.
(function () {
  const __modules = {};
  const __cache = {};
  function __require(name) {
    const key = name.replace("./", "").replace(".js", "");
    if (__cache[key]) return __cache[key].exports;
    const mod = { exports: {} };
    __cache[key] = mod;
    __modules[key](mod, mod.exports, __require);
    return mod.exports;
  }

`;

for (const file of files) {
  const key = file.replace(".js", "");
  const code = fs.readFileSync(path.join(SRC_DIR, file), "utf8");
  out += `  __modules[${JSON.stringify(key)}] = function (module, exports, require) {\n`;
  out += code;
  out += `\n  };\n\n`;
}

out += `  // Expose the phases we need on window.WasmCompiler for playground.html
  window.WasmCompiler = {
    Lexer: __require("lexer").Lexer,
    LexError: __require("lexer").LexError,
    Parser: __require("parser").Parser,
    ParseError: __require("parser").ParseError,
    Analyzer: __require("analyzer").Analyzer,
    SemanticError: __require("analyzer").SemanticError,
    CodeGen: __require("codegen").CodeGen,
  };
})();
`;

fs.writeFileSync(OUT_FILE, out, "utf8");
console.log(`Bundled ${files.length} modules -> ${OUT_FILE} (${(out.length / 1024).toFixed(1)} KB)`);
